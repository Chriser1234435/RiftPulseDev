/** RiftPulse V1 API contracts. Keep this package free of runtime platform dependencies. */
export const API_VERSION = "v1" as const;
export const SUPPORTED_MODULES = ["chat", "bsr-song-request"] as const;
export type ModuleKey = (typeof SUPPORTED_MODULES)[number];
export const PROVIDERS = ["twitch", "youtube", "kick", "tiktok"] as const;
export type ProviderKey = (typeof PROVIDERS)[number];
export type DevicePlatform = "pcvr" | "quest";

export interface ApiError {
  error: { code: string; message: string; requestId?: string };
}
export interface HealthResponse {
  service: "riftpulse-api"; status: "ok"; version: string; apiVersion: typeof API_VERSION;
}
export interface VersionResponse {
  service: "riftpulse-api"; version: string; apiVersion: typeof API_VERSION; modules: readonly ModuleKey[];
}
export interface CreatePairingChallengeRequest {
  /** Generated by the mod. The API must never log or return this value. */
  code: string;
  deviceId: string;
  platform: DevicePlatform;
  gameVersion: string;
  modVersion: string;
}
export interface CreatePairingChallengeResponse {
  challengeId: string; status: "pending"; expiresAt: string; pollAfterMs: number;
}
export interface ClaimPairingRequest { code: string; }
export interface ClaimPairingResponse {
  status: "claimed"; deviceId: string; platform: DevicePlatform; accountId: string;
}
export interface ModuleSetting {
  module: ModuleKey; enabled: boolean; settings: Record<string, unknown>; updatedAt: string;
}
export interface ChatCommand {
  id: string; command: string; module: "chat" | "bsr-song-request";
  action: "reply" | "request-song"; enabled: boolean; cooldownMs: number; config: Record<string, unknown>;
}
export interface SongRequestInput {
  provider: ProviderKey; requesterId: string; requesterName: string; input: string;
}
export interface SongRequest {
  id: string; provider: ProviderKey; requesterName: string; beatsaverKey: string;
  songName: string | null; status: "queued" | "playing" | "played" | "rejected" | "failed"; createdAt: string;
}
export interface ValidationIssue { path: string; message: string; }
export type ValidationResult<T> = { ok: true; value: T } | { ok: false; issues: ValidationIssue[] };

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
function isUuid(value: unknown): value is string {
  return typeof value === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value);
}

export function validateCreatePairingChallenge(input: unknown): ValidationResult<CreatePairingChallengeRequest> {
  if (!isRecord(input)) return { ok: false, issues: [{ path: "$", message: "Expected an object." }] };
  const issues: ValidationIssue[] = [];
  if (typeof input.code !== "string" || !/^\d{5}$/.test(input.code)) issues.push({ path: "code", message: "Must be exactly five digits." });
  if (!isUuid(input.deviceId)) issues.push({ path: "deviceId", message: "Must be a UUID." });
  if (input.platform !== "pcvr" && input.platform !== "quest") issues.push({ path: "platform", message: "Must be pcvr or quest." });
  if (typeof input.gameVersion !== "string" || input.gameVersion.length < 1 || input.gameVersion.length > 64) issues.push({ path: "gameVersion", message: "Must be 1–64 characters." });
  if (typeof input.modVersion !== "string" || input.modVersion.length < 1 || input.modVersion.length > 64) issues.push({ path: "modVersion", message: "Must be 1–64 characters." });
  if (issues.length) return { ok: false, issues };
  return { ok: true, value: {
    code: input.code as string, deviceId: input.deviceId as string, platform: input.platform as DevicePlatform,
    gameVersion: input.gameVersion as string, modVersion: input.modVersion as string,
  }};
}
export function validateClaimPairing(input: unknown): ValidationResult<ClaimPairingRequest> {
  if (!isRecord(input) || typeof input.code !== "string" || !/^\d{5}$/.test(input.code)) {
    return { ok: false, issues: [{ path: "code", message: "Must be exactly five digits." }] };
  }
  return { ok: true, value: { code: input.code } };
}
export function isModuleKey(value: unknown): value is ModuleKey {
  return typeof value === "string" && (SUPPORTED_MODULES as readonly string[]).includes(value);
}
export function isProviderKey(value: unknown): value is ProviderKey {
  return typeof value === "string" && (PROVIDERS as readonly string[]).includes(value);
}
